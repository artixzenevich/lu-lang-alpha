"""Модуль-плагин на Python для примера плагин.lu.

Подключается командой:
    подключить текст

Наружу видны все верхнеуровневые функции без подчёркивания
в начале имени. Значения lu-lang приходят «как есть»: числа как
числа, строки как строки, массивы как списки.
"""


def развернуть(строка):
    return строка[::-1]


def количество_слов(строка):
    return len(строка.split())


def звёзды(число):
    return "*" * int(число)