"""Встроенный модуль-плагин lu-lang на Python: время.

Подключение: подключить время

Наружу видны все верхнеуровневые функции без подчёркивания.
"""

import time


def метка():
    """Текущее время как дробное число секунд."""
    return time.time()


def часы():
    """Текущий час (0-23)."""
    return time.localtime().tm_hour


def минуты():
    """Текущие минуты (0-59)."""
    return time.localtime().tm_min