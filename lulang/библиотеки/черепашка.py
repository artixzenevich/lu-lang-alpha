"""Встроенный модуль-плагин lu-lang на Python: черепашка (графика).

Подключение: подключить черепашка

Команды рисуют на экране черепашкой, как в языке Logo. Окно появляется
при первом рисовании и остаётся открытым, пока его не закроют (после
команды «готово»). Нужен графический экран (Tkinter).
"""

import turtle

# Русские названия цветов -> английские имена, которые понимает Tk.
# Незнакомые значения (английские имена, #ff0000 и т.п.) передаются как есть.
_ЦВЕТА = {
    "чёрный": "black",
    "черный": "black",
    "белый": "white",
    "серый": "gray",
    "тёмно-серый": "darkgray",
    "светло-серый": "lightgray",
    "красный": "red",
    "тёмно-красный": "darkred",
    "оранжевый": "orange",
    "жёлтый": "yellow",
    "желтый": "yellow",
    "зелёный": "green",
    "зеленый": "green",
    "тёмно-зелёный": "darkgreen",
    "светло-зелёный": "lightgreen",
    "салатовый": "lightgreen",
    "бирюзовый": "turquoise",
    "голубой": "lightblue",
    "синий": "blue",
    "тёмно-синий": "darkblue",
    "фиолетовый": "purple",
    "сиреневый": "violet",
    "пурпурный": "magenta",
    "розовый": "pink",
    "бордовый": "maroon",
    "малиновый": "crimson",
    "коричневый": "brown",
    "золотой": "gold",
    "серебряный": "silver",
}

_черепаха = None


def _получить():
    """Создать черепаху при первом рисовании и вернуть её."""
    global _черепаха
    if _черепаха is None:
        _черепаха = turtle.Turtle()
    return _черепаха


def _перевести_цвет(имя):
    """Русское имя цвета -> английское для Tk; незнакомое вернуть как есть."""
    if isinstance(имя, str):
        return _ЦВЕТА.get(имя.strip().lower(), имя)
    return имя


def вперёд(шаги):
    """Пройти вперёд на указанное число шагов."""
    _получить().forward(шаги)


def назад(шаги):
    """Пройти назад на указанное число шагов."""
    _получить().backward(шаги)


def вправо(угол):
    """Повернуться вправо на угол (в градусах)."""
    _получить().right(угол)


def влево(угол):
    """Повернуться влево на угол (в градусах)."""
    _получить().left(угол)


def поднять_перо():
    """Перестать рисовать при движении."""
    _получить().penup()


def опустить_перо():
    """Начать рисовать при движении."""
    _получить().pendown()


def цвет(имя):
    """Задать цвет линии по имени: «красный», «синий», «зелёный» и другие
    русские названия (или по-английски: "red", "#ff0000")."""
    _получить().color(_перевести_цвет(имя))


def круг(радиус):
    """Нарисовать окружность заданного радиуса."""
    _получить().circle(радиус)


def точка():
    """Поставить точку."""
    _получить().dot()


def скорость(скорость_рисования):
    """Задать скорость черепахи: от 0 (мгновенно) до 10."""
    _получить().speed(скорость_рисования)


def готово():
    """Не закрывать окно с рисунком, пока его не закроют."""
    turtle.done()